# T3: everything derived from the transformed sources: the object list and
# module dependencies (src/Makevars.vendor), generated glue files, the
# public headers in inst/include/rmumps, and the struct-layout (ABI) record.

T3_GENERATED_HEADER <- "# GENERATED by tools/vendor.R from tools/vendor.lock and tools/manifest; do not edit."

# Headers in inst/include/rmumps that are written by hand, not generated.
t3_handwritten_headers <- function() c("rmumps_api.h")

# Modules defined and used by each Fortran file.
t3_modules <- function(files) {
  defs <- list(); uses <- list()
  for (f in names(files)) {
    if (!grepl("\\.[Ff]$", f)) next
    st <- ff_statements(files[[f]])
    m <- trimws(st$masked)
    d <- regmatches(m, regexec("^[Mm][Oo][Dd][Uu][Ll][Ee][[:space:]]+([A-Za-z0-9_]+)[[:space:]]*$", m))
    d <- toupper(vapply(d, function(x) if (length(x) == 2L) x[2L] else "", ""))
    d <- d[nzchar(d) & d != "PROCEDURE"]
    u <- regmatches(m, regexec("^[Uu][Ss][Ee]([[:space:]]*,[[:space:]]*[A-Za-z_]+)?[[:space:]]*(::)?[[:space:]]*([A-Za-z0-9_]+)", m))
    intr <- vapply(u, function(x) length(x) == 4L && grepl("INTRINSIC", toupper(x[2L])), FALSE)
    u <- toupper(vapply(u, function(x) if (length(x) == 4L) x[4L] else "", ""))
    u <- u[nzchar(u) & !intr]
    defs[[f]] <- unique(d)
    uses[[f]] <- unique(u)
  }
  list(defs = defs, uses = uses)
}

t3_wrap <- function(name, items, width = 76L) {
  if (!length(items)) return(paste0(name, " ="))
  out <- paste0(name, " = \\")
  out <- c(out, paste0("\t", items[-length(items)], " \\"), paste0("\t", items[length(items)]))
  out
}

t3_objects_mk <- function(comps) {
  mumps <- comps[["mumps"]]$files
  metis <- comps[["metis"]]$files
  obj <- function(prefix, f) paste0("vendor/", prefix, "/", sub("\\.(F|f|c)$", ".o", f))
  fsrc <- sort(names(mumps)[grepl("^(src|libseq)/.*\\.[Ff]$", names(mumps))], method = "radix")
  csrc <- sort(c(setdiff(names(mumps)[grepl("^(src|libseq)/.*\\.c$", names(mumps))], "src/mumps_c.c"),
                 "src/dmumps_c.c"), method = "radix")
  pord <- sort(names(mumps)[grepl("^PORD/lib/.*\\.c$", names(mumps))], method = "radix")
  msrc <- sort(names(metis)[grepl("\\.c$", names(metis))], method = "radix")
  mods <- t3_modules(mumps)
  provider <- character()
  for (f in names(mods$defs)) for (m in mods$defs[[f]]) {
    if (!is.na(provider[m])) stop("module ", m, " defined twice", call. = FALSE)
    provider[m] <- f
  }
  deps <- character()
  for (f in sort(names(mods$uses), method = "radix")) {
    p <- provider[mods$uses[[f]]]
    p <- sort(unique(p[!is.na(p) & p != f]), method = "radix")
    if (length(p))
      deps <- c(deps, paste0(obj("mumps", f), ": ", paste(obj("mumps", p), collapse = " ")))
  }
  c(T3_GENERATED_HEADER,
    "",
    t3_wrap("MUMPS_FOBJS", obj("mumps", fsrc)), "",
    t3_wrap("MUMPS_COBJS", obj("mumps", csrc)), "",
    t3_wrap("PORD_OBJS", obj("mumps", pord)), "",
    t3_wrap("METIS_OBJS", obj("metis", msrc)), "",
    "VENDOR_OBJS = $(MUMPS_FOBJS) $(MUMPS_COBJS) $(PORD_OBJS) $(METIS_OBJS)", "",
    "# Fixed-form preprocessed Fortran (.F): R's Makeconf resets .SUFFIXES and",
    "# has no rule for it, so every object gets an explicit rule.",
    unlist(lapply(fsrc, function(f) {
      s <- paste0("vendor/mumps/", f)
      c(paste0(obj("mumps", f), ": ", s),
        paste0("\t$(FC) $(ALL_FFLAGS) -c ", s, " -o ", obj("mumps", f)))
    })), "",
    "# Fortran module dependencies (from MODULE/USE statements)",
    deps)
}

t3_dmumps_c_wrapper <- function() {
  c("/* GENERATED by tools/vendor.R; do not edit.",
    " * Upstream builds dmumps_c.o from mumps_c.c with -DMUMPS_ARITH=MUMPS_ARITH_d. */",
    "#define MUMPS_ARITH MUMPS_ARITH_d",
    "#include \"mumps_c.c\"")
}

t3_generate <- function(comps, target) {
  mumps <- comps[["mumps"]]
  vend <- file.path(target, "src", "vendor")
  # glue files inside the vendor tree
  int_def <- mumps$files[["src/mumps_int_def32_h.in"]]
  write_lf(int_def, file.path(vend, "mumps", "include", "mumps_int_def.h"))
  write_lf(t3_dmumps_c_wrapper(), file.path(vend, "mumps", "src", "dmumps_c.c"))
  write_lf(t3_vendor_readme(comps), file.path(vend, "README.md"))
  # METIS ships only the Apache-2.0 notice; section 4(a) requires the text
  write_lf(read_lines(file.path("tools", "licenses", "Apache-2.0.txt")),
           file.path(vend, "metis", "LICENSE-Apache-2.0.txt"))
  # object list and module dependencies
  write_lf(t3_objects_mk(comps), file.path(target, "src", "Makevars.vendor"))
  # public headers
  inc <- file.path(target, "inst", "include", "rmumps")
  dir.create(inc, recursive = TRUE, showWarnings = FALSE)
  old <- setdiff(list.files(inc), t3_handwritten_headers())
  unlink(file.path(inc, old))
  for (h in c("dmumps_c.h", "mumps_c_types.h", "mumps_compat.h"))
    write_lf(mumps$files[[file.path("include", h)]], file.path(inc, h))
  write_lf(int_def, file.path(inc, "mumps_int_def.h"))
  t3_abi(comps, target)
}

t3_vendor_readme <- function(comps) {
  ver <- vapply(comps, function(cp) paste(cp$ent$Component, cp$ent$Version), "")
  c("# Vendored sources (generated)",
    "",
    "Everything under this directory is generated by `tools/vendor.R` from the",
    "pristine upstream tarballs pinned in `tools/vendor.lock`:",
    "",
    paste0("- ", ver),
    "",
    "Do not edit these files by hand; change the patches in `tools/patches/`",
    "or the transforms in `tools/transforms/` and regenerate (see",
    "`tools/README.md`). Files that differ from upstream start with a comment",
    "saying so. The changes are:",
    "",
    "- the numbered patches in `tools/patches/<component>/`;",
    "- T1 (Fortran): diagnostic WRITE/PRINT statements are commented out",
    "  (`C~` in columns 1-2), STOP becomes `CALL REXIT(...)`, INQUIRE results",
    "  are constant, RANDOM_NUMBER calls use a private generator, and file I/O",
    "  in the routines listed in `tools/manifest/mumps.dcf` is removed;",
    "- T2 (C): `#include \"rmumps_cshim.h\"` after the last `#include` of each",
    "  `.c` file (see `src/shim/rmumps_cshim.h`);",
    "- only the files needed for a sequential, double precision real build",
    "  are kept.",
    "",
    "MUMPS is distributed under the CeCILL-C license (`mumps/LICENSE`), METIS",
    "under the Apache License 2.0 (`metis/LICENSE.txt`).")
}

# Layout record, ABI number, public ABI header and adapters for older
# layouts. The registry and the records of older layouts are read from the
# source tree (they are history, not derived from the current tarball) and
# copied to `target`.
t3_abi <- function(comps, target) {
  src <- file.path("tools", "abi")
  out <- file.path(target, "tools", "abi")
  dir.create(out, recursive = TRUE, showWarnings = FALSE)
  reg <- abi_read_registry(src)
  if (!nrow(reg)) stop("tools/abi/registry.dcf is missing; see tools/README.md", call. = FALSE)
  rules <- t3_abi_rules(file.path(src, "rules.dcf"))
  ver <- comps[["mumps"]]$ent$Version
  cur <- abi_dump(file.path(target, "src", "vendor", "mumps", "include"))
  last <- abi_parse(read_lines(file.path(src, reg$Layout[nrow(reg)])))
  if (abi_same(last, cur)) {
    k <- reg$ABI[nrow(reg)]
  } else {
    k <- max(reg$ABI) + 1L
    lay <- sprintf("dmumps_struc_%s.txt", ver)
    reg <- rbind(reg, data.frame(ABI = k, MUMPS = ver, Layout = lay))
    write_lf(abi_format(cur, ver), file.path(out, lay))
    say("NEW DMUMPS_STRUC_C LAYOUT: ABI %d (MUMPS %s); review tools/abi and add adapter rules if needed", k, ver)
  }
  if (normalizePath(src) != normalizePath(out))
    for (f in c(reg$Layout, "rules.dcf"))
      if (file.exists(file.path(src, f)))
        file.copy(file.path(src, f), file.path(out, f), overwrite = TRUE)
  abi_write_registry(reg, file.path(out, "registry.dcf"))
  write_lf(c("/* GENERATED by tools/vendor.R from tools/abi/registry.dcf; do not edit. */",
             "#ifndef RMUMPS_ABI_H",
             "#define RMUMPS_ABI_H",
             sprintf("/* DMUMPS_STRUC_C layout of the MUMPS %s headers next to this file */", ver),
             sprintf("#define RMUMPS_DMUMPS_ABI %d", k),
             "#endif"),
           file.path(target, "inst", "include", "rmumps", "rmumps_abi.h"))
  # adapters for every older layout
  body <- character()
  reg_calls <- character()
  for (i in seq_len(nrow(reg))) {
    a <- reg$ABI[i]
    if (a == k) next
    old <- abi_parse(read_lines(file.path(src, reg$Layout[i])))
    body <- c(body, abi_adapter_c(old, cur, a, rules[[as.character(a)]]))
    reg_calls <- c(reg_calls,
      sprintf("  R_RegisterCCallable(\"rmumps\", \"rmumps_dmumps_c_safe_abi%d\", (DL_FUNC) rmumps_dmumps_c_safe_abi%d);", a, a),
      sprintf("  R_RegisterCCallable(\"rmumps\", \"rmumps_dmumps_c_abi%d\", (DL_FUNC) rmumps_dmumps_c_abi%d);", a, a))
    if (a == 1L)
      reg_calls <- c(reg_calls,
        "  /* legacy name of the raw entry point (rmumps <= 5.2.1-43) */",
        "  R_RegisterCCallable(\"rmumps\", \"dmumps_c\", (DL_FUNC) rmumps_dmumps_c_abi1);")
  }
  if (!any(reg$ABI == 1L & reg$ABI != k)) {
    reg_calls <- c(reg_calls,
      "  R_RegisterCCallable(\"rmumps\", \"dmumps_c\", (DL_FUNC) rmumps_dmumps_c_raw);")
  }
  write_lf(c("/* GENERATED by tools/vendor.R from tools/abi; do not edit.",
             sprintf(" * Adapters from older DMUMPS_STRUC_C layouts to ABI %d (MUMPS %s). */", k, ver),
             "#include \"rmumps_abi_adapter.h\"",
             "",
             body,
             "void rmumps_register_abi_adapters(void)",
             "{",
             reg_calls,
             "}"),
           file.path(target, "src", "rmumps_abi_adapters.c"))
}

# Adapter rules: one DCF record per (ABI, member) for members that exist only
# in an old layout. Field Out: C expression on the current struct `c`.
t3_abi_rules <- function(path) {
  if (!file.exists(path)) return(list())
  m <- read.dcf(path)
  rules <- list()
  for (i in seq_len(nrow(m))) {
    a <- m[i, "ABI"]
    if (is.null(rules[[a]])) rules[[a]] <- list()
    rules[[a]][[m[i, "Member"]]] <- list(out = m[i, "Out"])
  }
  rules
}
