# Layout (ABI) records of DMUMPS_STRUC_C and the generated adapters that let
# clients built for an older layout keep working.
#
# A layout record (tools/abi/dmumps_struc_<version>.txt) lists, for every
# member: name, declaration (with numeric array lengths), offset and size,
# measured by compiling a small C program against the headers. The ABI
# number of a layout is its position in tools/abi/registry.dcf; generate
# appends a new entry when the current headers give a layout that differs
# from the newest registered one.

abi_strip_comments <- function(txt) gsub("(?s)/\\*.*?\\*/", " ", txt, perl = TRUE)

# Members of `typedef struct { ... } DMUMPS_STRUC_C;` in the header text.
abi_parse_struct <- function(lines) {
  txt <- paste(lines, collapse = "\n")
  txt <- abi_strip_comments(txt)
  m <- regmatches(txt, regexec("typedef struct[[:space:]]*\\{(.*?)\\}[[:space:]]*DMUMPS_STRUC_C[[:space:]]*;", txt))[[1]]
  if (length(m) != 2L) stop("DMUMPS_STRUC_C not found", call. = FALSE)
  decls <- trimws(strsplit(m[2L], ";", fixed = TRUE)[[1]])
  decls <- gsub("[[:space:]]+", " ", decls[nzchar(decls)])
  out <- list()
  for (d in decls) {
    mm <- regmatches(d, regexec("^([A-Za-z_][A-Za-z0-9_]*) (.*)$", d))[[1]]
    if (length(mm) != 3L) stop("cannot parse member declaration: ", d, call. = FALSE)
    base <- mm[2L]
    for (v in trimws(strsplit(mm[3L], ",", fixed = TRUE)[[1]])) {
      ptr <- startsWith(v, "*")
      v <- trimws(sub("^\\*", "", v))
      nm <- sub("^([A-Za-z_][A-Za-z0-9_]*).*$", "\\1", v)
      dim <- if (grepl("\\[", v)) sub("^[^[]*\\[(.*)\\]$", "\\1", v) else ""
      if (grepl("\\]\\[", dim)) stop("multidimensional member not supported: ", v, call. = FALSE)
      out[[length(out) + 1L]] <- data.frame(name = nm, base = base, ptr = ptr, dim = dim)
    }
  }
  do.call(rbind, out)
}

abi_cc <- function() {
  cc <- system2(file.path(R.home("bin"), "R"), c("CMD", "config", "CC"), stdout = TRUE)
  cc[length(cc)]
}

# Measure the layout of DMUMPS_STRUC_C as declared in `incdir`/dmumps_c.h.
abi_dump <- function(incdir) {
  mem <- abi_parse_struct(read_lines(file.path(incdir, "dmumps_c.h")))
  tmp <- tempfile("abi")
  dir.create(tmp)
  on.exit(unlink(tmp, recursive = TRUE), add = TRUE)
  prog <- c("#include <stdio.h>", "#include <stddef.h>", "#include \"dmumps_c.h\"",
            "#define S DMUMPS_STRUC_C",
            "int main(void) {",
            "  printf(\"SIZE %lu %lu\\n\", (unsigned long) sizeof(S), (unsigned long) sizeof(void *));")
  for (i in seq_len(nrow(mem))) {
    f <- mem$name[i]
    el <- if (nzchar(mem$dim[i])) sprintf("sizeof(((S *) 0)->%s[0])", f) else "0"
    prog <- c(prog, sprintf(
      "  printf(\"%s %%lu %%lu %%lu\\n\", (unsigned long) offsetof(S, %s), (unsigned long) sizeof(((S *) 0)->%s), (unsigned long) %s);",
      f, f, f, el))
  }
  prog <- c(prog, "  return 0;", "}")
  writeLines(prog, file.path(tmp, "dump.c"))
  exe <- file.path(tmp, "dump")
  cmd <- sprintf("%s -I%s -o %s %s", abi_cc(), shQuote(normalizePath(incdir)), shQuote(exe),
                 shQuote(file.path(tmp, "dump.c")))
  if (system(cmd) != 0) stop("cannot compile the layout dumper", call. = FALSE)
  res <- system2(exe, stdout = TRUE)
  hdr <- strsplit(res[1L], " ")[[1]]
  rows <- do.call(rbind, strsplit(res[-1L], " "))
  mem$offset <- as.integer(rows[, 2L])
  mem$size <- as.integer(rows[, 3L])
  elsize <- as.integer(rows[, 4L])
  n <- ifelse(nzchar(mem$dim), mem$size %/% pmax(elsize, 1L), 0L)
  mem$decl <- paste0(mem$base, " ", ifelse(mem$ptr, "*", ""), mem$name,
                     ifelse(nzchar(mem$dim), paste0("[", n, "]"), ""))
  list(members = mem[, c("name", "decl", "offset", "size")],
       sizeof = as.integer(hdr[2L]), ptrsize = as.integer(hdr[3L]))
}

abi_format <- function(lay, version) {
  c(sprintf("# DMUMPS_STRUC_C layout of MUMPS %s (sizeof = %d, pointer size = %d)",
            version, lay$sizeof, lay$ptrsize),
    "# GENERATED by tools/vendor.R; columns: name|declaration|offset|size",
    sprintf("%s|%s|%d|%d", lay$members$name, lay$members$decl,
            lay$members$offset, lay$members$size))
}

abi_parse <- function(lines) {
  h <- regmatches(lines[1L], regexec("sizeof = ([0-9]+), pointer size = ([0-9]+)", lines[1L]))[[1]]
  body <- lines[!startsWith(lines, "#")]
  r <- do.call(rbind, strsplit(body, "|", fixed = TRUE))
  list(members = data.frame(name = r[, 1L], decl = r[, 2L], offset = as.integer(r[, 3L]),
                            size = as.integer(r[, 4L])),
       sizeof = as.integer(h[2L]), ptrsize = as.integer(h[3L]))
}

abi_same <- function(a, b) {
  identical(a$sizeof, b$sizeof) && identical(a$members$name, b$members$name) &&
    identical(a$members$decl, b$members$decl) && identical(a$members$offset, b$members$offset)
}

abi_read_registry <- function(dir) {
  p <- file.path(dir, "registry.dcf")
  if (!file.exists(p)) return(data.frame(ABI = integer(), MUMPS = character(), Layout = character()))
  l <- read_lines(p)
  m <- read.dcf(textConnection(l[!startsWith(l, "#")]))
  data.frame(ABI = as.integer(m[, "ABI"]), MUMPS = m[, "MUMPS"], Layout = m[, "Layout"])
}

abi_write_registry <- function(reg, path) {
  lines <- c("# ABI numbers of the DMUMPS_STRUC_C layouts rmumps has shipped.",
             "# Maintained by tools/vendor.R: a new entry is appended when the layout",
             "# changes. Never edit or remove an entry: clients are bound to them.", "")
  for (i in seq_len(nrow(reg)))
    lines <- c(lines, paste0("ABI: ", reg$ABI[i]), paste0("MUMPS: ", reg$MUMPS[i]),
               paste0("Layout: ", reg$Layout[i]), "")
  write_lf(lines[-length(lines)], path)
}

# C type of a member declaration without the name, and the name.
abi_decl_parts <- function(decl) {
  nm <- sub("^.*?\\**([A-Za-z_][A-Za-z0-9_]*)(\\[[0-9]+\\])?$", "\\1", decl, perl = TRUE)
  list(name = nm, array = grepl("\\[[0-9]+\\]$", decl), ptr = grepl("\\*", decl))
}

# Source of the adapter for an old layout `old` (ABI k) to the current
# layout `cur`. Members with the same name and declaration are copied both
# ways; char arrays whose length changed are copied as NUL-terminated
# strings; members only in the old layout get a rule from `rules` (named
# list: name -> list(out = "C expression on `cur`")) or are left zero.
abi_adapter_c <- function(old, cur, k, rules) {
  om <- old$members; cm <- cur$members
  ty <- sprintf("rmumps_dmumps_struc_abi%d", k)
  copy_in <- copy_out <- character()
  for (i in seq_len(nrow(om))) {
    nm <- om$name[i]
    j <- match(nm, cm$name)
    if (is.na(j)) {
      r <- rules[[nm]]
      if (is.null(r)) stop("no adapter rule for member '", nm, "' of ABI ", k, call. = FALSE)
      copy_out <- c(copy_out, sprintf("  o->%s = %s;", nm, r$out))
      next
    }
    od <- om$decl[i]; cd <- cm$decl[j]
    if (identical(od, cd)) {
      if (grepl("\\[[0-9]+\\]$", od)) {
        copy_in <- c(copy_in, sprintf("  memcpy(c->%s, o->%s, sizeof o->%s);", nm, nm, nm))
        copy_out <- c(copy_out, sprintf("  memcpy(o->%s, c->%s, sizeof o->%s);", nm, nm, nm))
      } else {
        copy_in <- c(copy_in, sprintf("  c->%s = o->%s;", nm, nm))
        copy_out <- c(copy_out, sprintf("  o->%s = c->%s;", nm, nm))
      }
    } else if (startsWith(od, "char ") && startsWith(cd, "char ") &&
               grepl("\\[[0-9]+\\]$", od) && grepl("\\[[0-9]+\\]$", cd)) {
      copy_in <- c(copy_in, sprintf("  copy_str(c->%s, sizeof c->%s, o->%s, sizeof o->%s);", nm, nm, nm, nm))
      copy_out <- c(copy_out, sprintf("  copy_str(o->%s, sizeof o->%s, c->%s, sizeof c->%s);", nm, nm, nm, nm))
    } else {
      stop("member '", nm, "' changed from '", od, "' to '", cd, "'; add an adapter rule", call. = FALSE)
    }
  }
  asserts <- sprintf("RMUMPS_ABI_ASSERT(offsetof(%s, %s) == %d);", ty, om$name, om$offset)
  c(sprintf("/* ---- ABI %d ---------------------------------------------------- */", k),
    "",
    sprintf("typedef struct {"),
    paste0("  ", om$decl, ";"),
    sprintf("} %s;", ty),
    "",
    "#if RMUMPS_ABI_CHECK_OFFSETS",
    sprintf("RMUMPS_ABI_ASSERT(sizeof(%s) == %d);", ty, old$sizeof),
    asserts,
    "#endif",
    "",
    sprintf("static void abi%d_copy_in(DMUMPS_STRUC_C *c, const %s *o)", k, ty),
    "{", copy_in, "}",
    "",
    sprintf("static void abi%d_copy_out(%s *o, const DMUMPS_STRUC_C *c)", k, ty),
    "{", copy_out, "}",
    "",
    sprintf("RMUMPS_ABI_ADAPTER(%d, %s)", k, ty),
    "")
}
